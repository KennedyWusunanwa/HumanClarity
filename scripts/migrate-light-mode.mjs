// ── tokenization ────────────────────────────────────────────────────────────
const tokens = new Map(); // literal(normalized) -> { name, light, dark }

function sanitize(s) {
  return s.replace(/[(),.%#]/g, (c) => ({ '(': '', ')': '', ',': '-', '.': '_', '%': 'p', '#': '' }[c]));
}

function nameForRgba(norm) {
  // norm like rgba(168,199,250,0.14) or rgb(1,2,3)
  const inner = norm.replace(/^rgba?\(/, '').replace(/\)$/, '');
  return '--r-' + inner.replace(/,/g, '-').replace(/\./g, '_');
}
function nameForHex(hex) { return '--h-' + hex.replace('#', ''); }

function registerRgba(norm) {
  if (tokens.has(norm)) return tokens.get(norm).name;
  const m = norm.match(/^rgba?\((\d+),(\d+),(\d+)(?:,([\d.]+))?\)$/);
  if (!m) return null;
  const [r, g, b] = [+m[1], +m[2], +m[3]];
  const a = m[4] === undefined ? undefined : parseFloat(m[4]);
  const name = nameForRgba(norm);
  tokens.set(norm, { name, dark: norm, light: lightForRgba(r, g, b, a) });
  return name;
}

function registerHex(hex) {
  const key = hex.toLowerCase();
  if (tokens.has(key)) return tokens.get(key).name;
  let light = HEX_LIGHT[key];
  if (!light) {
    const [r, g, b] = hexToRgb(key);
    const [lr, lg, lb] = lightRGB(r, g, b);
    light = `rgb(${lr},${lg},${lb})`;
  }
  const name = nameForHex(key);
  tokens.set(key, { name, dark: key, light });
  return name;
}

const RGBA_RE = /rgba?\(\s*\d+\s*,\s*\d+\s*,\s*\d+\s*(?:,\s*[\d.]+\s*)?\)/g;
const HEX_RE = /#[0-9a-fA-F]{6}(?![0-9a-fA-F])/g;

let totalReplacements = 0;
const perFile = {};

for (const rel of TARGET_FILES) {
  const path = resolve(ROOT, rel);
  let src = readFileSync(path, 'utf8');
  let count = 0;

  src = src.replace(RGBA_RE, (m) => {
    const norm = m.replace(/\s+/g, '');
    const name = registerRgba(norm);
    if (!name) return m;
    count++;
    return `var(${name})`;
  });

  src = src.replace(HEX_RE, (m) => {
    const hx = m.toLowerCase();
    if (hx === '#ffffff') return m; // keep white literal (on-accent, identical both modes)
    const name = registerHex(hx);
    count++;
    return `var(${name})`;
  });

  perFile[rel] = count;
  totalReplacements += count;
  if (!DRY) writeFileSync(path, src, 'utf8');
}

// ── emit CSS tokens into globals.css ────────────────────────────────────────
const entries = [...tokens.values()].sort((a, b) => a.name.localeCompare(b.name));
const lightLines = entries.map((t) => `  ${t.name}: ${t.light};`).join('\n');
const darkLines = entries.map((t) => `  ${t.name}: ${t.dark};`).join('\n');

const block = `${MARK_START}
/* ${entries.length} themeable color tokens. Dark = original literal (dark mode is
   pixel-identical to before); light = tuned equivalent. Toggle via .dark on <html>. */
:root {
${lightLines}
}
html.dark {
${darkLines}
}
${MARK_END}`;

if (!DRY) {
  let css = readFileSync(resolve(ROOT, CSS_FILE), 'utf8');
  const re = new RegExp(
    MARK_START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + MARK_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'),
    'g'
  );
  css = re.test(css) ? css.replace(re, block) : css.trimEnd() + '\n\n' + block + '\n';
  writeFileSync(resolve(ROOT, CSS_FILE), css, 'utf8');
}

console.log(`Tokens: ${entries.length}`);
console.log(`Replacements: ${totalReplacements}`, perFile);
if (DRY) console.log('(dry run — no files written)');
