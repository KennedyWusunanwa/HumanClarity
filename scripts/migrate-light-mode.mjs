// Light-mode migration: tokenize every hardcoded color literal (hex + rgba) in the
// app's inline styles into `var(--token)` references. Each token's DARK value is the
// original literal (so dark mode stays pixel-identical), and its LIGHT value is a tuned
// equivalent. The generated tokens are written into globals.css between markers; the
// switch happens purely by toggling `.dark` on <html>.
//
// Safe-by-construction: dark mode never changes (dark var = original literal).
//
// Usage:  node scripts/migrate-light-mode.mjs            (apply)
//         node scripts/migrate-light-mode.mjs --dry      (report only, no writes)

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DRY = process.argv.includes('--dry');

const TARGET_FILES = [
  'src/App.jsx',
  'app/admin/page.jsx',
  'app/page.jsx',
];
const CSS_FILE = 'app/globals.css';
const MARK_START = '/* === THEME-TOKENS-START (generated by scripts/migrate-light-mode.mjs) === */';
const MARK_END = '/* === THEME-TOKENS-END === */';

// ── color helpers ───────────────────────────────────────────────────────────
const clamp = (n, lo, hi) => Math.max(lo, Math.min(hi, n));
const round = (n) => Math.round(n * 1000) / 1000;

function lum(r, g, b) { return 0.299 * r + 0.587 * g + 0.114 * b; }

// Translate an opaque (r,g,b) accent/surface to its light-mode counterpart.
function lightRGB(r, g, b) {
  const L = lum(r, g, b);
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b), chroma = mx - mn;
  const reddish = r === mx && r - g > 30 && r - b > 30;
  const greenish = g === mx && g - r > 20 && g - b > 10;
  const bluish = b === mx && b - r > 40;

  if (L < 70) {
    // Dark fill / surface / overlay.
    if (reddish) return [220, 38, 38];     // dark red bg  -> red tint
    if (greenish) return [22, 163, 74];    // dark green bg -> green tint
    return [255, 255, 255];                // navy surface -> light surface
  }
  if (chroma < 40) {
    // Near-neutral.
    if (L >= 150) return [100, 116, 139];  // light slate -> slate-500
    return [r, g, b];
  }
  // Saturated hue (blue / purple / green / red / amber).
  if (L >= 150 && bluish) return [73, 104, 255]; // light-blue accent -> brand blue
  return [r, g, b];                              // keep hue (reads on light)
}

function lightAlpha(r, g, b, a) {
  // Boost opacity of dark surfaces so cards read as crisp panels on a light bg.
  const L = lum(r, g, b);
  if (r === 0 && g === 0 && b === 0) return clamp(a * 0.6, 0, 0.25); // softer shadows
  if (L < 70 && !(r > g + 30 && r > b + 30) && !(g > r + 20)) {
    return a >= 0.5 ? clamp(a + 0.22, 0, 1) : a;
  }
  return a;
}

function lightForRgba(r, g, b, a) {
  if (r === 0 && g === 0 && b === 0) {
    // Drop shadows: keep dark but softened (a white "shadow" would vanish on light).
    if (a === undefined) return 'rgb(15,23,42)';
    return `rgba(15,23,42,${round(clamp(a * 0.6, 0, 0.22))})`;
  }
  if (r === 255 && g === 255 && b === 255) {
    // White overlay on dark -> faint dark overlay on light.
    return `rgba(15,23,42,${round(clamp(a * 1.3, 0, 0.12))})`;
  }
  if (a === undefined) {
    const [lr, lg, lb] = lightRGB(r, g, b);
    return `rgb(${lr},${lg},${lb})`;
  }
  const [lr, lg, lb] = lightRGB(r, g, b);
  const la = lightAlpha(r, g, b, a);
  return `rgba(${lr},${lg},${lb},${round(la)})`;
}

function hexToRgb(hex) {
  const h = hex.replace('#', '');
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
}

